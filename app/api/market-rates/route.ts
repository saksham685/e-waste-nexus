export async function GET() {
  // Add subtle live jitter to simulate continuous stock market price movements
  const liveCommodities = COMMODITIES.map((c) => {
    const jitter = (Math.random() - 0.48) * (c.pricePerUnit * 0.003);
    const updatedPrice = Math.round((c.pricePerUnit + jitter) * 100) / 100;
    return {
      ...c,
      pricePerUnit: updatedPrice,
      lastUpdated: new Date().toISOString(),
    };
  });

  return NextResponse.json(
    {
      success: true,
      commodities: liveCommodities,
      worldNews: WORLD_NEWS,
      globalStats: {
        globalEwastePerSecondKg: 1965,
        totalFormalRecycledPercent: 22.3,
        unrecoveredValueUsdBillion: 91.5,
        timestamp: new Date().toISOString(),
      },
    },
    {
      headers: {
        'Cache-Control': 'public, s-maxage=10, stale-while-revalidate=30',
      },
    }
  );
}
